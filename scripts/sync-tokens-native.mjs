// Writes the Okara Design System variables (tests/figma-tokens.json, read from Figma) into
// mobile/src/theme/tokens.ts for the native app. Same source as scripts/sync-tokens.mjs (web CSS).
//   node scripts/sync-tokens-native.mjs          write
//   node scripts/sync-tokens-native.mjs --check  exit 1 if the file is out of date (used by the tests)
// Colours are resolved to hex (React Native has no CSS variables). Names keep the Figma path in camelCase:
// Color/surface/accent-light -> color.surfaceAccentLight, Surface/space/tags-indent -> space.tagsIndent (Mobile mode).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../tests/figma-tokens.json', import.meta.url), 'utf8'));
const outPath = new URL('../mobile/src/theme/tokens.ts', import.meta.url);

export const camel = (s) => s.replace(/[/-]+([a-z0-9])/gi, (_, c) => c.toUpperCase());
const strip = (name, prefix) => (name.startsWith(prefix + '/') ? name.slice(prefix.length + 1) : name);
// DM Sans / Martian Mono static cuts shipped by @expo-google-fonts (one family name per weight in React Native).
const FONT = {
  sans: { 400: 'DMSans_400Regular', 500: 'DMSans_500Medium', 600: 'DMSans_600SemiBold' },
  mono: { 400: 'MartianMono_400Regular', 500: 'MartianMono_500Medium', 600: 'MartianMono_600SemiBold' },
};

export function build(t) {
  const prim = {};
  for (const [k, v] of Object.entries(t.Primitives)) prim[k] = String(v).toLowerCase();
  const color = {};
  for (const [k, v] of Object.entries(t.Color)) color[camel(k)] = v && v.alias ? prim[v.alias] : String(v).toLowerCase();
  const primitive = Object.fromEntries(Object.entries(prim).map(([k, v]) => [camel(k), v]));
  // The app is phones only: Surface in its Mobile mode (the web gets Desktop by default, Mobile under 640px).
  const surf = Object.entries(t.Surface).map(([k, v]) => [k, v.Mobile]);
  const space = Object.fromEntries(surf.filter(([k]) => k.startsWith('space/')).map(([k, v]) => [camel(strip(k, 'space')), v]));
  const radius = Object.fromEntries(surf.filter(([k]) => k.startsWith('radius/')).map(([k, v]) => [camel(strip(k, 'radius')), v]));
  const opacity = Object.fromEntries(Object.entries(t.Opacity).map(([k, v]) => [camel(strip(k, 'opacity')), v > 1 ? v / 100 : Math.round(v * 100) / 100]));
  const text = {};
  for (const [k, s] of Object.entries(t.TextStyles || {})) {
    const fam = FONT[s.family] || FONT.sans;
    const style = { fontFamily: fam[s.weight] || fam[500], fontSize: s.size };
    if (s.lineHeight != null) style.lineHeight = s.lineHeight;
    if (s.letterSpacing) style.letterSpacing = Math.round(s.size * s.letterSpacing) / 100; // Figma % of font size -> points
    text[camel(k.replace(/\//g, '-'))] = style;
  }
  const body = [
    '// Generated by scripts/sync-tokens-native.mjs from tests/figma-tokens.json (Okara Design System, Figma\n' +
    '// 7glNMA9d7iVJFf2CvyrzAb). Do not edit by hand: change Figma, update the JSON, run the script.',
    `export const primitive = ${JSON.stringify(primitive, null, 2)} as const;`,
    `export const color = ${JSON.stringify(color, null, 2)} as const;`,
    `export const space = ${JSON.stringify(space, null, 2)} as const;`,
    `export const radius = ${JSON.stringify(radius, null, 2)} as const;`,
    `export const opacity = ${JSON.stringify(opacity, null, 2)} as const;`,
    `export const text = ${JSON.stringify(text, null, 2)} as const;`,
    '',
  ];
  return body.join('\n\n');
}

const out = build(tokens);
if (process.argv.includes('--check')) {
  const cur = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (cur !== out) { console.error('mobile/src/theme/tokens.ts is out of date: run node scripts/sync-tokens-native.mjs'); process.exit(1); }
  console.log('mobile tokens up to date');
} else {
  writeFileSync(outPath, out);
  console.log('mobile/src/theme/tokens.ts written');
}
