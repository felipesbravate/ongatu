// node scripts/sync-illustrations.mjs [--check] [folder]
// Preserve the full exported SVG, including clip paths, transforms and precision.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { svgMetadata, camel } from './svg-assets.mjs';
const check = process.argv.includes('--check');
const dir = resolve(process.argv.slice(2).find(a => !a.startsWith('--')) || new URL('../Illustrations', import.meta.url).pathname);
const publicDir = new URL('../public/illustrations/', import.meta.url);
if (!check) mkdirSync(publicDir, { recursive: true });
const files = readdirSync(dir).filter(f => f.endsWith('.svg')).map(file => {
  const stem = file.replace(/\.svg$/, '');
  const m = stem.match(/^(.*)-(\d+)$/);
  return { file, base: m ? m[1] : stem, n: m ? Number(m[2]) : 0 };
}).sort((a, b) => a.base.localeCompare(b.base, 'en') || a.n - b.n);
const entries = files.map(({ file, base, n }) => {
  const svg = readFileSync(join(dir, file), 'utf8');
  const { width, height, viewBox, hash } = svgMetadata(svg, file);
  const name = camel(base) + (n ? n + 1 : '');
  const dest = new URL(encodeURIComponent(file), publicDir);
  if (check) { if (readFileSync(dest, 'utf8') !== svg) throw new Error(`${file}: public export differs from source`); }
  else writeFileSync(dest, svg);
  return { name, file, asset: `/illustrations/${encodeURIComponent(file)}?v=${hash}`, viewBox, width, height };
});
if (!entries.length || new Set(entries.map(e => e.name)).size !== entries.length) throw new Error('Missing or duplicate illustrations');
const content = '// Generated by scripts/sync-illustrations.mjs. Exact artwork lives in public/illustrations/.\n' +
  entries.map(e => `export const ${e.name} = ${JSON.stringify(e)};`).join('\n') +
  `\n\nexport const all = [${entries.map(e => e.name).join(', ')}];\n`;
const output = new URL('../src/ui/illustrations.js', import.meta.url);
if (check) { if (readFileSync(output, 'utf8') !== content) throw new Error('illustrations.js is out of date'); }
else writeFileSync(output, content);
console.log(`${entries.length} illustrations ${check ? 'verified' : 'synced'}`);
